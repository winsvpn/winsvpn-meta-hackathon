package carrierhost

// Generation of the per-platform carrier-profile key lists.
//
// The content lives in the package rather than in cmd/winn-carrier-keys so that
// servedkeys_test.go can assert the checked-in files match it without shelling
// out to the generator. The command writes; the test verifies; both read the
// same function, so "the generator would produce something different" and "the
// test passes" cannot both be true.

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// GeneratedFile is one platform's key list: where it lives relative to the
// repository root, and exactly what it must contain.
type GeneratedFile struct {
	Path    string
	Content string
}

// ResolveRepositoryRoot returns the repository root. An explicit path is
// validated and returned; an empty one is found by walking up from the working
// directory looking for the two markers that only the root has.
func ResolveRepositoryRoot(explicit string) (string, error) {
	isRoot := func(dir string) bool {
		if _, err := os.Stat(filepath.Join(
			dir, "winn_protocol_experimental", "go.mod")); err != nil {
			return false
		}
		_, err := os.Stat(filepath.Join(dir, "pubspec.yaml"))
		return err == nil
	}

	if strings.TrimSpace(explicit) != "" {
		absolute, err := filepath.Abs(explicit)
		if err != nil {
			return "", err
		}
		if !isRoot(absolute) {
			return "", fmt.Errorf(
				"%s is not the repository root: expected it to contain both "+
					"winn_protocol_experimental/go.mod and pubspec.yaml",
				absolute)
		}
		return absolute, nil
	}

	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if isRoot(dir) {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New(
				"could not find the repository root above the working " +
					"directory; pass -root")
		}
		dir = parent
	}
}

// generatedBanner is the first line of every generated file. It names the
// command that writes it and the declaration it is derived from, so a reader
// who finds one of these files by grep is told immediately where to make the
// change instead of editing the copy.
func generatedBanner(comment string) string {
	return comment + " Code generated by " +
		"winn_protocol_experimental/cmd/winn-carrier-keys. DO NOT EDIT.\n" +
		comment + "\n" +
		comment + " Source of truth: winn_protocol_experimental/datapath/" +
		"carrierhost/servedkeys.go\n" +
		comment + " Regenerate:      cd winn_protocol_experimental && " +
		"go run ./cmd/winn-carrier-keys\n" +
		comment + "\n" +
		comment + " carrierhost.Profile decodes with DisallowUnknownFields, so " +
		"every key below is a\n" +
		comment + " field that really exists in the schema and a key that is " +
		"NOT below is a hard\n" +
		comment + " parse failure in the engine rather than a warning. " +
		"servedkeys_test.go proves\n" +
		comment + " both halves: that this file matches the Go declaration, " +
		"and that the Go\n" +
		comment + " declaration matches Profile's own json tags.\n"
}

// GeneratedPlatformKeyFiles returns every generated file and its exact
// content, in a stable order.
func GeneratedPlatformKeyFiles() []GeneratedFile {
	return []GeneratedFile{
		{
			Path:    "android/app/src/main/kotlin/org/winsvpn/app/WinnCarrierProfileKeys.kt",
			Content: kotlinKeysFile(),
		},
		{
			Path:    "apple/WinsTunnelCore/WinsWinnCarrierProfileKeys.swift",
			Content: swiftKeysFile(),
		},
		{
			Path:    "lib/winn_carrier_profile_keys.dart",
			Content: dartKeysFile(),
		},
		{
			Path:    "linux/runner/linux_winn_carrier_profile_keys.h",
			Content: cppKeysFile(),
		},
	}
}

func indentedList(keys []string, indent, open, closeQuote string) string {
	var out strings.Builder
	for _, key := range keys {
		out.WriteString(indent)
		out.WriteString(open)
		out.WriteString(key)
		out.WriteString(closeQuote)
		out.WriteString("\n")
	}
	return out.String()
}

func kotlinKeysFile() string {
	var out strings.Builder
	out.WriteString(generatedBanner("//"))
	out.WriteString(`
package org.winsvpn.app

/**
 * The carrier-profile keys, generated from the engine's own schema.
 *
 * [SERVED] is every ` + "`protocol_params`" + ` / ` + "`[winn]`" + ` key that describes a carrier
 * profile. [SPA] is the single-packet-authorization subset of it.
 *
 * ` + "`spa_key_path`" + ` is deliberately absent from every list here. It names a FILE
 * ON THIS DEVICE, resolved against this app's own credential directory, and a
 * served path would let whoever answered the config request choose which file
 * the engine opens. The key it names is a credential: neither it nor its
 * contents may appear in a served config, in profile JSON as a value, or in a
 * log line.
 */
internal object WinnCarrierProfileKeys {

    /** Every served carrier-profile key. */
    val SERVED: Set<String> = setOf(
`)
	out.WriteString(indentedList(ServedProfileKeys, "        ", `"`, `",`))
	out.WriteString(`    )

    /** The served keys with no safe default. No spa_* key is required. */
    val SERVED_REQUIRED: Set<String> = setOf(
`)
	out.WriteString(indentedList(RequiredServedProfileKeys, "        ", `"`, `",`))
	out.WriteString(`    )

    /**
     * The single-packet-authorization subset.
     *
     * Every one is inert unless ` + "`spa_mode`" + ` is "required", and the engine
     * REFUSES a document that sets any of them to a NON-EMPTY value without the
     * mode. An EMPTY value is not refused -- it is indistinguishable from
     * absent. Omit these when SPA is off because omission cannot be misread and
     * because only a non-empty stray is a hard failure, NOT because emitting
     * them empty would fail.
     */
    val SPA: Set<String> = setOf(
`)
	out.WriteString(indentedList(SPAServedProfileKeys, "        ", `"`, `",`))
	out.WriteString(`    )

    /** ` + "`spa_mode`" + ` values. */
    const val SPA_MODE_OFF = "` + SPAModeOff + `"
    const val SPA_MODE_REQUIRED = "` + SPAModeRequired + `"

    /**
     * The SPA key file's name inside the credential directory, alongside the
     * six that were already there. One hex-encoded key per line, and EXACTLY
     * ONE line for a client -- the engine refuses a multi-key client file
     * rather than guessing, because during a rotation the wrong guess is
     * silent.
     */
    const val SPA_KEY_CREDENTIAL_FILE_NAME = "` + SPAKeyCredentialFileName + `"
}
`)
	return out.String()
}

