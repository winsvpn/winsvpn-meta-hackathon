NFT_IPTABLES_ONLY = {"nftables": [
    {"metainfo": {"version": "1.0.9", "json_schema_version": 1}},
    {"table": {"family": "ip", "name": "nat", "handle": 1}},
    {"chain": {"family": "ip", "table": "nat", "name": "OUTPUT", "handle": 1, "type": "nat", "hook": "output",
               "prio": -100, "policy": "accept"}},
    {"rule": {"family": "ip", "table": "nat", "chain": "OUTPUT", "handle": 9, "expr": [
        {"xt": {"type": "match", "name": "addrtype"}}, {"jump": {"target": "DOCKER"}}]}},
]}


def nft_table(family, table, chains):
    """chains: {name: (type, hook, [expr lists])}; a hook of None is a regular chain."""
    items = [{"metainfo": {"version": "1.0.9"}}, {"table": {"family": family, "name": table}}]
    for name, (ctype, hook, rules) in chains.items():
        c = {"family": family, "table": table, "name": name}
        if hook:
            c.update({"type": ctype, "hook": hook, "prio": 0, "policy": "accept"})
        items.append({"chain": c})
        for i, expr in enumerate(rules):
            items.append({"rule": {"family": family, "table": table, "chain": name, "handle": 10 + i, "expr": expr}})
    return {"nftables": items}


def M(field, right, op="==", proto="ip"):
    return {"match": {"op": op, "left": {"payload": {"protocol": proto, "field": field}}, "right": right}}


SPORT_9111 = M("sport", 9111, proto="udp")
L4_UDP = {"match": {"op": "==", "left": {"meta": {"key": "l4proto"}}, "right": "udp"}}


class Matcher(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.mkdtemp(prefix="winn3-rewrite-")
        cls.py = os.path.join(cls.tmp, "matcher.py")
        with open(cls.py, "w") as f:
            f.write(matcher_source())

    def run_matcher(self, ipt=FLEET_NAT, legacy=LEGACY_EMPTY, nft=NFT_IPTABLES_ONLY, listen="0.0.0.0:9111", uid=994,
                    routes=ROUTES, addrs=ADDRS, explain=False):
        paths = []
        for name, body in (("ipt", ipt), ("legacy", legacy), ("nft", json.dumps(nft) if isinstance(nft, dict) else nft),
                           ("routes", routes), ("addrs", addrs)):
            p = os.path.join(self.tmp, name)
            with open(p, "w") as f:
                f.write(body)
            paths.append(p)
        env = dict(os.environ, EGRESS_REWRITE_EXPLAIN="1" if explain else "0")
        r = subprocess.run([sys.executable, "-I", "-S", "-B", self.py] + paths + [listen, str(uid)],
                           capture_output=True, text=True, env=env)
        return r.returncode, [l for l in r.stdout.splitlines() if l]

    def refuses(self, needle, **kw):
        rc, out = self.run_matcher(**kw)
        self.assertEqual(rc, 0, out)
        self.assertTrue(any(needle in l for l in out), "no finding with %r: %s" % (needle, out))
        return out

    def passes(self, **kw):
        rc, out = self.run_matcher(**kw)
        self.assertEqual((rc, out), (0, []))

    # --- the fleet's shapes pass, each for a stated reason -----------------
    def test_fleet_shape_passes_with_reasons(self):
        rc, out = self.run_matcher(explain=True)
        self.assertEqual(rc, 0)
        self.assertFalse([l for l in out if not l.startswith("ok ")], out)
        want = [
            ("-A OUTPUT ! -d 127.0.0.0/8 -m addrtype --dst-type LOCAL -j DOCKER", "destination type"),
            ("-A WINN3GW-NAT-POSTROUTING -s 10.10.0.0/24 -o eth0 -j MASQUERADE", "source prefix"),
            ("-A POSTROUTING -s 172.17.0.0/16 ! -o docker0 -j MASQUERADE", "source prefix"),
            ("-A WINVPN-NAT-POSTROUTING -s 10.8.0.0/16 -o eth0 -j MASQUERADE", "source prefix"),
        ]
        for rule, why in want:
            self.assertTrue(any(rule in l and why in l for l in out), "%s (%s) not explained: %s" % (rule, why, out))

    def test_listener_on_the_tunnel_address_is_not_excluded(self):
        # Bound to the v3 tunnel address, the MASQUERADE for 10.10.0.0/24 can match its replies.
        self.refuses("WINN3GW-NAT-POSTROUTING -s 10.10.0.0/24", listen="10.10.0.1:9111")

    def test_reply_sources_for_a_wildcard_listener(self):
        # A route that may carry a public client through awg0 makes awg0's address a possible source.
        routes = ROUTES + "45.0.0.0/16 dev awg0 scope link\n"
        self.refuses("WINVPN-NAT-POSTROUTING -s 10.8.0.0/16", routes=routes)

    # --- one refusal per rewrite type ------------------------------------
    def test_nat_output_dnat(self):
        ipt = FLEET_NAT.replace("-A POSTROUTING -j WINN3GW",
                                "-A OUTPUT -p udp -m udp --sport 9111 -j DNAT --to-destination 198.51.100.5\n-A POSTROUTING -j WINN3GW")
        self.refuses("nat OUTPUT: -A OUTPUT -p udp -m udp --sport 9111 -j DNAT", ipt=ipt)

    def test_nat_postrouting_masquerade_without_a_source_match(self):
        ipt = FLEET_NAT.replace("-A POSTROUTING -j WINVPN", "-A POSTROUTING -o eth0 -j MASQUERADE\n-A POSTROUTING -j WINVPN")
        self.refuses("nat POSTROUTING: -A POSTROUTING -o eth0 -j MASQUERADE", ipt=ipt)

    def test_nat_postrouting_snat_restoring_the_source(self):
        ipt = FLEET_NAT.replace("-A POSTROUTING -j WINVPN",
                                "-A POSTROUTING -s 192.0.2.99/32 -p udp -j SNAT --to-source 192.0.2.125\n"
                                "-A POSTROUTING -s 192.0.2.125/32 -p udp -j SNAT --to-source 192.0.2.99\n-A POSTROUTING -j WINVPN")
        out = self.refuses("-s 192.0.2.125/32 -p udp -j SNAT", ipt=ipt)
        self.assertFalse(any("192.0.2.99/32 -p udp" in l for l in out), out)  # that source is not the gateway's

    def test_mangle_output_mark_and_tos(self):
        for target in ("MARK --set-xmark 0x1/0xffffffff", "TOS --set-tos 0x10/0xff", "CONNMARK --set-xmark 0x1/0xff"):
            ipt = FLEET_NAT.replace(":WINN3GW-MANGLE-FORWARD - [0:0]\n",
                                    ":WINN3GW-MANGLE-FORWARD - [0:0]\n-A OUTPUT -p udp -j %s\n" % target)
            self.refuses("mangle OUTPUT: -A OUTPUT -p udp -j %s" % target.split()[0], ipt=ipt)

    def test_nfqueue_in_filter_output(self):
        # A queued packet can be changed in userspace; the kernel re-routes it on reinjection.
        ipt = FLEET_NAT.replace("*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n",
                                "*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n"
                                "-A OUTPUT -p udp -j NFQUEUE --queue-num 0\n")
        self.refuses("filter OUTPUT: -A OUTPUT -p udp -j NFQUEUE", ipt=ipt)

    def test_a_jump_to_a_chain_that_rewrites(self):
        ipt = FLEET_NAT.replace(":DOCKER - [0:0]\n", ":DOCKER - [0:0]\n:REWRITE - [0:0]\n").replace(
            "-A POSTROUTING -j WINVPN", "-A OUTPUT -j REWRITE\n-A REWRITE -d 198.51.100.0/24 -j DNAT --to-destination 198.51.100.5\n"
            "-A POSTROUTING -j WINVPN")
        self.refuses("nat OUTPUT: -A REWRITE -d 198.51.100.0/24 -j DNAT", ipt=ipt)

    def test_an_unknown_match_proves_nothing(self):
        ipt = FLEET_NAT.replace("-A POSTROUTING -j WINVPN", "-A OUTPUT -m mark --mark 0x1 -j DNAT --to-destination 198.51.100.5\n"
                                "-A POSTROUTING -j WINVPN")
        self.refuses("-m mark --mark 0x1 -j DNAT", ipt=ipt)

    def test_legacy_tables_are_read(self):
        legacy = LEGACY_EMPTY.replace(":POSTROUTING ACCEPT [71:6748]\n",
                                      ":POSTROUTING ACCEPT [71:6748]\n-A OUTPUT -p udp -j DNAT --to-destination 198.51.100.5\n")
        self.refuses("iptables-legacy nat OUTPUT: -A OUTPUT -p udp -j DNAT", legacy=legacy)

    def test_nft_route_chain_rewrite(self):
        nft = nft_table("inet", "l80", {"out": ("route", "output", [
            [L4_UDP, SPORT_9111, {"mangle": {"key": {"payload": {"protocol": "ip", "field": "saddr"}}, "value": "192.0.2.126"}}]])})
        self.refuses("nft inet l80 out (route hook output): rule handle 10 (mangle)", nft=nft)

    def test_nft_postrouting_restore_and_nat(self):
        restore = {"mangle": {"key": {"payload": {"protocol": "ip", "field": "saddr"}}, "value": "192.0.2.125"}}
        for stmt, kind in ((restore, "mangle"), ({"snat": {"addr": "192.0.2.125"}}, "snat"), ({"masquerade": None}, "masquerade"),
                           ({"dnat": {"addr": "198.51.100.5"}}, "dnat"), ({"redirect": None}, "redirect")):
            nft = nft_table("ip", "l80", {"post": ("filter", "postrouting", [[stmt]])})
            self.refuses("(%s)" % kind, nft=nft)

    def test_nft_queue_xt_and_marks(self):
        for stmt, kind in (({"queue": {"num": 0}}, "queue"), ({"xt": {"type": "target", "name": "DNAT"}}, "xt"),
                           ({"mangle": {"key": {"meta": {"key": "mark"}}, "value": 1}}, "mangle"),
                           ({"mangle": {"key": {"ct": {"key": "mark"}}, "value": 1}}, "mangle")):
            nft = nft_table("inet", "fw", {"out": ("filter", "output", [[stmt]])})
            self.refuses("(%s)" % kind, nft=nft)

    def test_nft_jump_is_followed(self):
        nft = nft_table("inet", "fw", {"out": ("filter", "output", [[{"jump": {"target": "sub"}}]]),
                                        "sub": (None, None, [[{"snat": {"addr": "192.0.2.9"}}]])})
        self.refuses("nft inet fw out (filter hook output): rule handle 10 (snat)", nft=nft)

    def test_nat_input_snat_on_the_clients_datagrams(self):
        # The gateway replies to the SNAT address; conntrack restores the real
        # client at LOCAL_OUT and the kernel routes the reply again.
        ipt = FLEET_NAT.replace("-A PREROUTING -i amn0", "-A INPUT -p udp -m udp --dport 9111 -j SNAT --to-source 10.81.1.7\n-A PREROUTING -i amn0")
        self.refuses("iptables nat INPUT: -A INPUT -p udp -m udp --dport 9111 -j SNAT", ipt=ipt)
        for rule in ("-A INPUT -p tcp -j SNAT --to-source 10.81.1.7",
                     "-A INPUT -p udp -m udp --dport 53 -j SNAT --to-source 10.81.1.7",
                     "-A INPUT -p udp -m multiport --dports 53,123 -j SNAT --to-source 10.81.1.7",
                     "-A INPUT -d 10.99.0.0/16 -j SNAT --to-source 10.81.1.7",
                     "-A INPUT -m addrtype --dst-type BROADCAST -j SNAT --to-source 10.81.1.7",
                     "-A INPUT -p udp -j ACCEPT"):
            self.passes(ipt=FLEET_NAT.replace("-A PREROUTING -i amn0", rule + "\n-A PREROUTING -i amn0"))
        # The replies' own exclusions do not apply inbound: a source match on the
        # gateway's address says nothing about the client's datagrams.
        self.refuses("-A INPUT -s 10.20.0.0/16", ipt=FLEET_NAT.replace(
            "-A PREROUTING -i amn0", "-A INPUT -s 10.20.0.0/16 -j SNAT --to-source 10.81.1.7\n-A PREROUTING -i amn0"))

    def test_nft_nat_input(self):
        snat = {"snat": {"addr": "10.81.1.7"}}
        nft = nft_table("inet", "n", {"in": ("nat", "input", [[M("dport", 9111, proto="udp"), snat]])})
        self.refuses("nft inet n in (nat hook input): rule handle 10 (snat)", nft=nft)
        for match in (M("dport", 22, proto="tcp"), M("dport", 53, proto="udp"),
                      M("daddr", {"prefix": {"addr": "10.99.0.0", "len": 16}})):
            self.passes(nft=nft_table("inet", "n", {"in": ("nat", "input", [[match, snat]])}))
        # a filter-type input chain cannot SNAT; its verdicts are not read
        self.passes(nft=nft_table("inet", "f", {"in": ("filter", "input", [[{"drop": None}]])}))

    # --- exclusions that make a rewriting rule harmless ------------------
    def test_exclusions_pass(self):
        for rule in ("-A OUTPUT -p tcp -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT ! -p udp -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -p udp -m udp --sport 53 -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -p udp -m udp ! --sport 9111 -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -p udp -m multiport --sports 53,123 -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -o docker0 -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -s 10.20.0.0/16 -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -m owner --uid-owner 0 -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -m owner ! --uid-owner 994 -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -m addrtype --dst-type LOCAL -j DNAT --to-destination 198.51.100.5",
                     "-A OUTPUT -p udp -j ACCEPT",
                     "-A OUTPUT -p udp -m comment --comment \"just a counter\""):
            self.passes(ipt=FLEET_NAT.replace("-A POSTROUTING -j WINVPN", rule + "\n-A POSTROUTING -j WINVPN"))

    def test_matches_that_do_not_exclude(self):
        # Each is one step away from an exclusion above and must still refuse.
        for rule, needle in (("-A OUTPUT -m addrtype --dst-type UNICAST -j DNAT --to-destination 198.51.100.5", "--dst-type UNICAST"),
                             ("-A OUTPUT -m addrtype ! --dst-type LOCAL -j DNAT --to-destination 198.51.100.5", "! --dst-type LOCAL"),
                             ("-A POSTROUTING ! -o docker0 -j MASQUERADE", "! -o docker0"),
                             ("-A POSTROUTING -o eth+ -j MASQUERADE", "-o eth+"),
                             ("-A POSTROUTING ! -s 10.0.0.0/8 -j MASQUERADE", "! -s 10.0.0.0/8"),
                             ("-A OUTPUT -p udp -m udp --sport 9000:9200 -j DNAT --to-destination 198.51.100.5", "--sport 9000:9200")):
            self.refuses(needle, ipt=FLEET_NAT.replace("-A POSTROUTING -j WINVPN", rule + "\n-A POSTROUTING -j WINVPN"))
        # ...and their excluding twins pass: replies leave only through eth0.
        for rule in ("-A POSTROUTING ! -o eth0 -j MASQUERADE", "-A POSTROUTING -o wg+ -j MASQUERADE",
                     "-A POSTROUTING ! -s 192.0.2.0/24 -j MASQUERADE"):
            self.passes(ipt=FLEET_NAT.replace("-A POSTROUTING -j WINVPN", rule + "\n-A POSTROUTING -j WINVPN"))
        fib = {"match": {"op": "==", "left": {"fib": {"result": "type", "flags": ["daddr"]}}, "right": "unicast"}}
        self.refuses("(snat)", nft=nft_table("inet", "fw", {"post": ("nat", "postrouting", [[fib, {"snat": {"addr": "192.0.2.9"}}]])}))
        oif = {"match": {"op": "!=", "left": {"meta": {"key": "oifname"}}, "right": "eth0"}}
        self.passes(nft=nft_table("inet", "fw", {"post": ("nat", "postrouting", [[oif, {"masquerade": None}]])}))

    def test_owner_match_needs_a_known_uid(self):
        rule = "-A OUTPUT -m owner --uid-owner 0 -j DNAT --to-destination 198.51.100.5"
        self.refuses("--uid-owner 0", ipt=FLEET_NAT.replace("-A POSTROUTING -j WINVPN", rule + "\n-A POSTROUTING -j WINVPN"), uid=-1)
        self.refuses("--uid-owner 994", uid=994, ipt=FLEET_NAT.replace(
            "-A POSTROUTING -j WINVPN", "-A OUTPUT -m owner --uid-owner 994 -j DNAT --to-destination 198.51.100.5\n-A POSTROUTING -j WINVPN"))

    def test_nft_exclusions_pass(self):
        rewrite = {"snat": {"addr": "192.0.2.9"}}
        for match in (M("dport", 22, proto="tcp"),
                      {"match": {"op": "==", "left": {"meta": {"key": "l4proto"}}, "right": {"set": ["tcp", "icmp"]}}},
                      {"match": {"op": "!=", "left": {"meta": {"key": "l4proto"}}, "right": "udp"}},
                      M("sport", {"set": [53, {"range": [1000, 2000]}]}, proto="udp"),
                      M("saddr", {"prefix": {"addr": "10.8.0.0", "len": 16}}),
                      {"match": {"op": "==", "left": {"meta": {"key": "oifname"}}, "right": "docker*"}},
                      {"match": {"op": "==", "left": {"meta": {"key": "skuid"}}, "right": 0}},
                      {"match": {"op": "==", "left": {"fib": {"result": "type", "flags": ["daddr"]}}, "right": "local"}}):
            nft = nft_table("inet", "fw", {"post": ("nat", "postrouting", [[match, rewrite]])})
            self.passes(nft=nft)
        # verdicts, counters, logs and set updates cannot rewrite
        nft = nft_table("inet", "fw", {"out": ("filter", "output", [
            [{"match": {"op": "in", "left": {"ct": {"key": "state"}}, "right": ["established"]}}, {"accept": None}],
            [{"counter": {"packets": 1, "bytes": 2}}, {"log": {"prefix": "x"}}, {"drop": None}]])})
        self.passes(nft=nft)

    def test_nft_values_it_cannot_read_prove_nothing(self):
        rewrite = {"snat": {"addr": "192.0.2.9"}}
        nft = nft_table("inet", "fw", {"post": ("nat", "postrouting", [[M("saddr", "@allowed"), rewrite]])})
        self.refuses("(snat)", nft=nft)

    def test_ipv6_and_iptables_owned_nft_tables_are_skipped_in_json(self):
        nft = nft_table("ip6", "t", {"post": ("nat", "postrouting", [[{"masquerade": None}]])})
        self.passes(nft=nft)
        self.passes(nft=NFT_IPTABLES_ONLY)  # its xt expressions are read through iptables-save

    def test_unparsable_inputs_fail(self):
        for kw in ({"ipt": FLEET_NAT + "# Table `nat' is incompatible, use 'nft' tool.\n"},
                   {"nft": "not json"},
                   {"listen": "nowhere"},
                   {"routes": "10.0.0.0/8 dev eth9\n"},  # no route may carry a public client
                   {"addrs": ""},  # a wildcard listener and no known address: a source match would prove nothing
                   {"ipt": "-A OUTPUT -j DNAT\n"}):
            rc, out = self.run_matcher(**kw)
            self.assertEqual(rc, 2, (kw, out))
            self.assertTrue(out and out[0].startswith("unparsable"), out)


