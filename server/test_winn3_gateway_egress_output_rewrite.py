def matcher_source():
    with open(INSTALLER) as f:
        text = f.read()
    m = re.search(r"<<'EGRESS_REWRITE_PY'\n(.*?)\nEGRESS_REWRITE_PY\n", text, re.S)
    assert m, "the embedded matcher is missing"
    return m.group(1) + "\n"


