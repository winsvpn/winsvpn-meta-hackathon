"""Build the root-owned runner from the installer's authoritative pure helpers.

No code is read from the app's writable deployed directory. The generated
artifact shares the exact descriptor verifier and profile render with the app.
"""
import ast
import builtins
import hashlib
from pathlib import Path
import symtable
import sys


def build(installer, cli):
    source = installer.split('cat > "${APP_DIR}/main.py" <<\'PYEOF\'\n', 1)[1].split('\nPYEOF\n', 1)[0]
    tree = ast.parse(source)
    definitions = {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            definitions[node.name] = node
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for target in targets:
                if isinstance(target, ast.Name):
                    definitions[target.id] = node
    # parse_iso_datetime is the CLI's marker parser, shared with the app's
    # freshness gate so the two cannot order a release and a flip differently.
    wanted = {"winn3_render_canary_profile", "winn3_probe_canary", "winn3_write_canary_file",
              "winn3_canary_bindings", "winn3_result_binding", "parse_iso_datetime"}
    # The CLI owns its read-only connection. Binding lookup receives that
    # connection through get_db, supplied by the CLI below.
    supplied = {"get_db", "logger"}
    imports = []
    imported = set()
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            modules = [a.name for a in node.names] if isinstance(node, ast.Import) else [node.module]
            if all(m and m.split('.')[0] in sys.stdlib_module_names for m in modules):
                imports.append(ast.get_source_segment(source, node))
                imported.update(a.asname or (a.name.split('.')[0] if isinstance(node, ast.Import) else a.name) for a in node.names)
    known = imported | supplied | set(dir(builtins))
    selected = set()
    referenced = set()
    while wanted - selected:
        name = sorted(wanted - selected)[0]
        if name not in definitions:
            if name in known:
                selected.add(name)
                continue
            raise ValueError("Unresolved runner dependency: " + name)
        node = definitions[name]
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.decorator_list:
            raise ValueError("Runner cannot include decorated app code: " + name)
        text = ast.get_source_segment(source, node)
        symbols = symtable.symtable(text, '<runner>', 'exec')
        dependencies = set()
        def visit(scope):
            dependencies.update(s.get_name() for s in scope.get_symbols() if s.is_global() and s.is_referenced())
            for child in scope.get_children():
                visit(child)
        visit(symbols)
        referenced.update(dependencies)
        wanted.update(dependencies - known)
        selected.add(name)
    nodes = {id(definitions[name]) for name in selected if name in definitions}
    imports = []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            aliases = [a for a in node.names if (a.asname or (a.name.split('.')[0] if isinstance(node, ast.Import) else a.name)) in referenced & imported]
            if aliases:
                node.names = aliases
                imports.append(ast.unparse(node))
    declarations = [ast.get_source_segment(source, node) for node in tree.body if id(node) in nodes]
    output = ('# Generated by server/build_h3_canary_runtime.py. Do not edit.\n'
              'from __future__ import annotations\n' + '\n'.join(imports) +
              '\nimport logging\nlogger = logging.getLogger("winn3-canary")\n\n' +
              '\n\n'.join(declarations) + '\n\n' + cli)
    compile(output, '<runner>', 'exec')
    return output


if __name__ == '__main__':
    root = Path(__file__).resolve().parent
    output = build((root / 'wins_control_plane_setup_ONETOUCH.sh').read_text(),
                   (root / 'h3_canary_cli.py.inc').read_text())
    target = root / 'wins_winn3_canary_runtime.py'
    target.write_text(output)
    print('Runner SHA-256:', hashlib.sha256(output.encode()).hexdigest())
