// PAC script generation.
//
// Three properties matter here, and each is a bug this file exists to prevent
// rather than a feature it exists to add.
//
// 1. NO "; DIRECT" FALLBACK, EVER.
//    A PAC return value of "SOCKS5 127.0.0.1:1080; DIRECT" tells the browser to
//    connect directly when the proxy is unreachable. That one semicolon turns a
//    circumvention tool into one that quietly sends the user's traffic over the
//    plaintext path at the moment they are least protected. The token "DIRECT"
//    appears below only for hosts the user deliberately put outside the tunnel,
//    never as a fallback.
//
// 2. NO NAME RESOLUTION INSIDE THE PAC.
//    The PAC helpers dnsResolve(), isInNet(), isResolvable() and myIpAddress()
//    all perform a lookup. A PAC that calls dnsResolve() sends the hostname to
//    the local resolver before the browser has even decided to proxy it, which
//    defeats the point of resolving names at the far end. Only pure string
//    comparison is used here.
//
// 3. NO UNCAUGHT EXCEPTION.
//    If FindProxyForURL throws, a browser's proxy resolver falls back to a
//    direct connection. So the whole body is wrapped and the catch returns the
//    proxy: fail closed even on a fault in our own generated code.

import { MODE_LISTED } from './constants.js';
import { pacToken } from './endpoint.js';

function lit(s) {
  return JSON.stringify(String(s));
}

/**
 * @param {{mode: string, listed: string[], excluded: string[]}} settings
 * @param {{kind: string, host: string, port: number}} endpoint
 * @returns {string} PAC source
 */
export function buildPac(settings, endpoint) {
  const tokenLit = lit(pacToken(endpoint));
  const listed = (settings.listed || []).map(lit).join(',');
  const excluded = (settings.excluded || []).map(lit).join(',');
  const listedMode = settings.mode === MODE_LISTED;

  return `// Generated by the Win's VPN browser proxy. Do not edit.
// Routing only. Performs no name resolution, and has no DIRECT fallback for
// in-scope hosts: if the local endpoint is down, in-scope requests fail rather
// than leaving over the direct connection.
var P = ${tokenLit};
var LISTED = [${listed}];
var EXCLUDED = [${excluded}];
var LISTED_MODE = ${listedMode ? 'true' : 'false'};

function wvMatch(rule, host) {
  if (host === rule) { return true; }
  var rLen = rule.length;
  var hLen = host.length;
  if (hLen <= rLen) { return false; }
  var diff = hLen - rLen;
  return host.charCodeAt(diff - 1) === 46 && host.lastIndexOf(rule) === diff;
}

function wvAny(rules, host) {
  for (var i = 0; i < rules.length; i++) {
    if (wvMatch(rules[i], host)) { return true; }
  }
  return false;
}

function FindProxyForURL(url, host) {
  try {
    var h = ("" + host).toLowerCase();
    if (h.charAt(h.length - 1) === ".") { h = h.substring(0, h.length - 1); }
    if (LISTED_MODE) {
      // Only listed hosts are routed. Everything else was never claimed to be
      // protected, so it goes direct.
      return wvAny(LISTED, h) ? P : "DIRECT";
    }
    // Everything is routed except hosts the user put outside the tunnel by name.
    return wvAny(EXCLUDED, h) ? "DIRECT" : P;
  } catch (e) {
    // Fail closed. A fault in this script must not become a direct connection.
    return ${tokenLit};
  }
}
`;
}

/** A PAC that routes nothing. Used when handing the browser back untouched. */
export const PAC_ALL_DIRECT =
  'function FindProxyForURL(url, host) { return "DIRECT"; }\n';

/**
 * Fail-closed PAC for the one case buildPac can throw (an endpoint that
 * validateEndpoint rejects). Routing to a dead loopback port means in-scope
 * requests FAIL: never a DIRECT fallback, and never traffic to whatever
 * malformed address the endpoint carried (Round 37 cross-examination: a
 * first-run throw used to leave the browser with no proxy at all, which is
 * the exact fail-open this extension exists to close).
 */
export const PAC_FAIL_CLOSED =
  'function FindProxyForURL(url, host) { return "PROXY 127.0.0.1:1"; }\n';
