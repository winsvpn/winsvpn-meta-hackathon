def verify_all():
    with open("web/i18n/languages.json") as f:
        langs = json.load(f)
    missing = []
    for l in langs:
        code = l["code"].lower()
        if code not in FLAG_MAP:
            import re
            m = re.search(r"[-_]([a-z]{2})$", code)
            if not m:
                missing.append((l["code"], l["name"]))
    if missing:
        print(f"Missing {len(missing)} flags:")
        for c, n in missing:
            print(f"  '{c}': '{n}'")
        sys.exit(1)
    print(f"Verified all {len(langs)} languages have a valid flag emoji!")

if __name__ == "__main__":
    verify_all()
