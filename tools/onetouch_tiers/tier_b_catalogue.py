def run(cmd, rc=0, capture=None, timeout=1800, note="", private=False):
    """`private` keeps the output out of the evidence (its sha256 and size are logged): identity material only."""
    step = {"kind": "run", "cmd": cmd, "rc": rc, "capture": capture, "timeout": timeout, "note": note}
    if private:
        step["private"] = True
    return step


def expect(capture, how, value, note=""):
    return {"kind": "expect", "capture": capture, "how": how, "value": value, "note": note}


def shim(shims, note=""):
    return {"kind": "shim", "shims": shims, "note": note}


def unshim():
    return {"kind": "unshim"}


def owner(text):
    return {"kind": "owner", "text": text}


def hub(text):
    return {"kind": "hub", "text": text}


def local(args, capture=None, stdin_capture=None, rc=0, note=""):
    """A hub-lite command on the operator Mac: `python3 -I -B tools/onetouch_tiers/hub_lite.py ARGS --state {hublite_state}`."""
    return {"kind": "local", "argv": list(args), "capture": capture, "stdin_capture": stdin_capture, "rc": rc, "note": note}


def evaluate(name, fn, args, stop=False):
    return {"kind": "evaluate", "name": name, "fn": fn, "args": list(args), "stop": stop}


def staging_checks():
    """Every scenario that claims `installer-staged` first proves it, and stops there if the staging is short."""
    return [run(STAGING_CHECK, capture="staging", rc=None, timeout=120),
            evaluate("staging", "evaluate_staging", ["staging", "@installer_sha256", "@binary_pin"], stop=True)]


def scenario(identifier, design, steps, requires=(), destructive=False, profile="quick", outline=False):
    return {"id": identifier, "design": design, "steps": steps, "requires": tuple(requires),
            "destructive": destructive, "profile": profile, "outline": outline}


def late_failure_checks(label):
    """The checks every forced late failure ends with, before any reboot (5.3 snapshot fallback)."""
    return [
        run("systemctl is-active winn3-gateway.service; true", capture=label + "_gw"),
        expect(label + "_gw", "not_contains", "\nactive\n", "the gateway is stopped"),
        run("test -e /var/lib/winsvpn/winn3-late-failure.json && cat /var/lib/winsvpn/winn3-late-failure.json", capture=label + "_record"),
        expect(label + "_record", "regex", r'"stage":"[A-D]"', "the record names the stage"),
        run("bash {work}/s7_probe_from_ns.sh 9111 443 80", capture=label + "_probe"),
        expect(label + "_probe", "not_contains", "answered", "UDP and TCP 9111, 443 and 80 are not answered from a client namespace"),
    ]


