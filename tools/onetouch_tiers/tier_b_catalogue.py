"""The Tier B scenario catalogue (design v17 5.3, 5.7).

Tier B runs the real installer and real systemd on a real or full-system guest: the amd64t colima guest or an
owner-named host. These steps have NEVER been executed by the lane that wrote them. They are written from the
design text and the installer source, and `tests/test_winn3_onetouch_s7.py` checks their structure (every
placeholder resolves, every shim regex compiles, every forbidden command is absent). The first real run may need
adjustment; the report says so.

A scenario is a list of steps. Step kinds:
  run      a shell command on the target as root. rc is the expected status (None = any).
  expect   a check on a captured output.
  shim     install command shims (shims.py) and put them first on PATH for the `{installer_run}` placeholder.
  unshim   remove them.
  owner    a checkpoint only the owner can do (a reboot of the guest, a provider-console run, a phone). The
           harness stops there and prints the instruction; `tier_b.py resume` continues.
  hub      a hub-side action described in words (kept where the hub-lite CLI cannot yet do it).
  local    a hub-lite command on the OPERATOR MAC (tools/onetouch_tiers/hub_lite.py against a scratch state directory);
           it never contacts a host. `stdin_capture` feeds an earlier capture to it on stdin.
  evaluate a pure judgement (readbacks.py, then tierb_eval.py) over earlier captures; `stop` ends the scenario on a fail.

`requires` lists what must exist before the scenario is meaningful; the runner refuses to start one whose
requirement is not declared satisfied with `--have`.
"""
