"""Command shims for forced failures in Tier B (design 5.3: "a forced failure after phase B and before phase C", "a harness wrapper makes ... fail", "a harness flock held from just before the exit path starts").

The installer has no failure-injection hook, and the lane adds none: production text stays as certified. A shim is a
small script placed first on the PATH the harness gives the installer. It runs the real command, except when one of its
rules fires. A rule can fail the Nth matching call, create a marker file (so a later shim can key on it), or start a
background `flock` that holds a lock file (the contention fixtures hold the guard's lock from exactly the moment the
exit path starts, which is the moment the forced failure happens).

The generator is plain text out, tested on the operator Mac against a fake "real" command.
"""
import json
import re
import shlex


def _q(text):
    return shlex.quote(text)


def shim_script(real, rules, state_dir="/run/s7-shims.state"):
    """A bash shim for the command at path `real`.

    Each rule is a dict:
      match         regex tested against the argument string (required)
      requires      marker file that must exist for the rule to apply (optional)
      sets          marker file to create when the rule fires (optional)
      nth           fire on the Nth matching call counted per rule (default 1)
      every         if true, fire on every matching call from the Nth (default: only the Nth)
      fail          exit status to return instead of running the command (optional; absent = run it)
      hold_lock     lock file to hold with `flock -x` when the rule fires (optional)
      hold_seconds  how long the background holder lives (default 30)
      held_file     file to create when the rule fires, before any wait (optional)
      wait_file     when the rule fires, wait until this file exists before failing or running (optional); the harness
                    creates it when the variant's interference is in place, so a forced failure happens at a chosen moment
      wait_seconds  the bound on that wait (default 3600); past it the rule proceeds and logs `wait-timeout`
      message       text for stderr when failing
    """
    for rule in rules:
        if "match" not in rule:
            raise ValueError("a shim rule needs match")
        re.compile(rule["match"])
    lines = ["#!/bin/bash", "# generated by tools/onetouch_tiers/shims.py; removed by the harness after the scenario",
             "REAL=%s" % _q(real), "STATE=%s" % _q(state_dir), 'mkdir -p "${STATE}"', 'args="$*"',
             'echo "$(date +%s.%N) ${args}" >> "${STATE}/$(basename "$0").log"']
    for index, rule in enumerate(rules):
        counter = '"${STATE}/$(basename "$0").rule%d"' % index
        lines.append("RE%d=%s" % (index, _q(rule["match"])))
        cond = '[[ "${args}" =~ ${RE%d} ]]' % index
        if rule.get("requires"):
            cond += " && [[ -e %s ]]" % _q(rule["requires"])
        nth = int(rule.get("nth", 1))
        lines.append("if %s; then" % cond)
        lines.append("  n=$(( $(cat %s 2>/dev/null || echo 0) + 1 )); echo \"${n}\" > %s" % (counter, counter))
        fire = "[[ \"${n}\" -ge %d ]]" % nth if rule.get("every") else "[[ \"${n}\" == %d ]]" % nth
        lines.append("  if %s; then" % fire)
        if rule.get("sets"):
            lines.append("    : > %s" % _q(rule["sets"]))
        if rule.get("held_file"):
            lines.append("    : > %s" % _q(rule["held_file"]))
        if rule.get("wait_file"):
            lines.append("    w=0; while [[ ! -e %s && ${w} -lt %d ]]; do sleep 0.2; w=$((w + 1)); done"
                         % (_q(rule["wait_file"]), int(rule.get("wait_seconds", 3600)) * 5))
            # exactly one of the two lines: `released` when the harness created the file, `wait-timeout` when it never did
            lines.append("    if [[ -e %s ]]; then echo \"$(date +%%s.%%N) released\"; else echo \"$(date +%%s.%%N) wait-timeout\"; fi"
                         " >> \"${STATE}/$(basename \"$0\").log\"" % _q(rule["wait_file"]))
        if rule.get("hold_lock"):
            lines.append("    ( flock -x %s sleep %d ) >/dev/null 2>&1 &" % (_q(rule["hold_lock"]), int(rule.get("hold_seconds", 30))))
            lines.append("    sleep 0.3")
        if "fail" in rule:
            message = rule.get("message", "s7 shim: injected failure")
            lines.append("    printf '%%s\\n' %s >&2" % _q(message))
            lines.append("    exit %d" % int(rule["fail"]))
        lines.append("  fi")
        lines.append("fi")
    lines.append('exec "${REAL}" "$@"')
    return "\n".join(lines) + "\n"


def install_commands(shim_dir, shims):
    """Shell lines that install the shims. `shims` maps command name -> (real path, rules)."""
    out = ["install -d -m 700 %s" % _q(shim_dir)]
    for name, (real, rules) in sorted(shims.items()):
        body = shim_script(real, rules, state_dir=shim_dir + ".state")
        out.append("cat > %s <<'S7_SHIM_EOF'\n%sS7_SHIM_EOF" % (_q(shim_dir + "/" + name), body))
        out.append("chmod 755 %s" % _q(shim_dir + "/" + name))
    return "\n".join(out)


def remove_commands(shim_dir):
    return "rm -rf %s %s" % (_q(shim_dir), _q(shim_dir + ".state"))


def describe(shims):
    return json.dumps({k: v[1] for k, v in shims.items()}, sort_keys=True)
