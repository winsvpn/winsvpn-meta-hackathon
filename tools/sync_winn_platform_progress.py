#!/usr/bin/env python3
"""Regenerate the LIVE PROGRESS section of WINN_PROTOCOL_PLATFORM_PLAN.md.

Each lane agent writes only its own `.winn_platform_progress/<lane>.json`, so
parallel lanes never collide on the plan document. This script folds those
files into the single plan file.

Run it any time:  python3 tools/sync_winn_platform_progress.py

Exit codes: 0 synced, 1 plan file missing or markers absent.
"""

from __future__ import annotations

import json
import pathlib
import sys
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).resolve().parent.parent
PLAN = ROOT / "WINN_PROTOCOL_PLATFORM_PLAN.md"
PROGRESS_DIR = ROOT / ".winn_platform_progress"

BEGIN = "<!-- BEGIN:LIVE_PROGRESS -->"
END = "<!-- END:LIVE_PROGRESS -->"

LANE_ORDER = ["datapath", "android", "apple", "windows", "conformance"]

STATUS_MARK = {
    "not_started": "&#9675; not started",
    "in_progress": "&#9679; in progress",
    "blocked": "&#9632; BLOCKED",
    "done": "&#10003; done",
    "failed": "&#10007; failed",
}


def load_lane(path: pathlib.Path) -> dict | None:
    try:
        with path.open(encoding="utf-8") as handle:
            data = json.load(handle)
    except json.JSONDecodeError as exc:
        # A half-written file from a live agent is expected, not an error.
        return {
            "lane": path.stem,
            "status": "in_progress",
            "summary": f"progress file not parseable yet ({exc.msg})",
            "_partial": True,
        }
    except OSError as exc:
        print(f"warn: cannot read {path.name}: {exc}", file=sys.stderr)
        return None
    if not isinstance(data, dict):
        return None
    data.setdefault("lane", path.stem)
    return data


def render(lanes: list[dict]) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")
    out: list[str] = [f"_Synced {stamp}. Regenerated by `tools/sync_winn_platform_progress.py` -- do not hand-edit._", ""]

    if not lanes:
        out.append("No lane has reported yet.")
        return "\n".join(out)

    out.append("| Lane | Status | Done | Summary |")
    out.append("|---|---|---|---|")
    for lane in lanes:
        status = STATUS_MARK.get(str(lane.get("status", "")), str(lane.get("status", "unknown")))
        steps = lane.get("steps") or []
        if isinstance(steps, list) and steps:
            complete = sum(1 for s in steps if isinstance(s, dict) and s.get("done"))
            done = f"{complete}/{len(steps)}"
        else:
            done = "--"
        summary = str(lane.get("summary", "")).replace("|", "\\|").replace("\n", " ")
        if len(summary) > 160:
            summary = summary[:157] + "..."
        out.append(f"| `{lane.get('lane')}` | {status} | {done} | {summary} |")

    for lane in lanes:
        detail_parts = [lane.get("steps"), lane.get("blocked_on"), lane.get("verified"), lane.get("notes")]
        if not any(detail_parts):
            continue
        out.extend(["", f"### {lane.get('lane')}"])

        steps = lane.get("steps") or []
        if isinstance(steps, list):
            for step in steps:
                if not isinstance(step, dict):
                    continue
                box = "[x]" if step.get("done") else "[ ]"
                note = f" -- {step['note']}" if step.get("note") else ""
                out.append(f"- {box} {step.get('title', 'untitled')}{note}")

        blocked = lane.get("blocked_on")
        if blocked:
            out.append("")
            out.append(f"**BLOCKED:** {blocked}")

        verified = lane.get("verified")
        if verified:
            out.append("")
            out.append("**Verified by real command output:**")
            items = verified if isinstance(verified, list) else [verified]
            for item in items:
                out.append(f"- {item}")

        notes = lane.get("notes")
        if notes:
            out.append("")
            out.append(str(notes))

    return "\n".join(out)


def main() -> int:
    if not PLAN.exists():
        print(f"error: {PLAN} does not exist", file=sys.stderr)
        return 1

    text = PLAN.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print("error: LIVE_PROGRESS markers missing from the plan file", file=sys.stderr)
        return 1

    lanes: list[dict] = []
    if PROGRESS_DIR.is_dir():
        seen = set()
        for name in LANE_ORDER:
            path = PROGRESS_DIR / f"{name}.json"
            if path.exists():
                lane = load_lane(path)
                if lane:
                    lanes.append(lane)
                    seen.add(path.name)
        for path in sorted(PROGRESS_DIR.glob("*.json")):
            if path.name in seen:
                continue
            lane = load_lane(path)
            if lane:
                lanes.append(lane)

    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    PLAN.write_text(f"{head}{BEGIN}\n{render(lanes)}\n{END}{tail}", encoding="utf-8")

    print(f"synced {len(lanes)} lane(s) into {PLAN.name}")
    for lane in lanes:
        print(f"  {lane.get('lane'):<12} {lane.get('status')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
